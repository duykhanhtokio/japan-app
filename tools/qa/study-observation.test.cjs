const assert = require('node:assert/strict');
const Q = require('./study-observation.js');
const meta = { sector: 'agriculture', anonymousLearner: 'learner-A', deviceModel: 'physical model supplied by tester', os: 'tester OS', buildLabel: 'development test build', locale: 'vi', courseScope: '1go', studyDay: 'day1', contentIds: 'actual-lesson-id', buildCommit: 'a'.repeat(40), target: 'nativeApp' };
const s = Q.create(meta, 0);
assert.throws(() => Q.create({ ...meta, buildCommit: 'main' }, 0));
assert.throws(() => Q.create({ ...meta, contentIds: '' }, 0));
assert.throws(() => Q.segment(s, 'japanese', -1, 0, 500));
assert.throws(() => Q.segment(s, 'japanese', 60000, 0, 500));
Q.segment(s, 'japanese', 60000, 0, 60000);
Q.segment(s, 'questions', 30000, 120000, 150000);
assert.equal(Q.summary(s).activeMinutes, 1.5);
Q.recover(s, 300000);
assert.equal(Q.summary(s).activeMinutes, 1.5, 'reload/recovery gap is not learning time');
assert.equal(s.status, 'paused');
assert.throws(() => Q.setCheck(s, 'coldStart', 'pass', '', ''));
Q.setCheck(s, 'coldStart', 'blocked', 'app not installed on phone', 'operator-notes-01');
assert.throws(() => Q.finish(s, 300000), /completed/);
s.observation.completed = false;
s.observation.comprehension = 'Fixture only; not a real learner result';
Q.finish(s, 300000);
assert.equal(s.review.physicalDeviceVerified, false);
assert.equal(s.review.learnerDurationAccepted, false);
assert.equal(s.acceptance, 'human_report_pending_evidence_review');
assert.throws(() => Q.segment(s, 'japanese', 1, 0, 1));
assert.throws(() => Q.setCheck(s, 'coldStart', 'pass', 'x', 'y'));
const z = Q.create(meta, 0); z.observation = { completed: true, comprehension: 'fixture' };
assert.throws(() => Q.finish(z, 1), /No actual/);
console.log('PASS_OBSERVATION_CLOCK: unit conversions, pause gaps, recovery, evidence requirements, immutable finished sessions; synthetic fixtures are not learner/device evidence');
