import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {stripTypeScriptTypes} from 'node:module';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import vm from 'node:vm';

const root = fileURLToPath(new URL('../', import.meta.url));
const baseline = process.argv[2] || 'HEAD';
const read = path => JSON.parse(readFileSync(resolve(root, path), 'utf8'));
const previous = path => JSON.parse(execFileSync('git', ['show', `${baseline}:${path}`], {cwd: root, maxBuffer: 4e6}));
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const counts = {n5: 7, n4: 8, n3: 6, n2: 5, n1: 6};
const numerals = {5: '五', 6: '六', 7: '七', 8: '八'};
let total = 0;
for (const level of Object.keys(counts)) for (let i = 1; i <= 6; i++) {
  const n = String(i).padStart(2, '0'), base = `src/data/jlpt-original/${level}/${n}`;
  const master = read(`${base}/master.ja.json`), old = previous(`${base}/master.ja.json`);
  const audio = read(`${base}/audio.manifest.json`), org = read(`${base}/listening-organization.ja.json`);
  const oldAudio = previous(`${base}/audio.manifest.json`), oldOrg = previous(`${base}/listening-organization.ja.json`);
  assert.deepEqual(master.questions, old.questions, `${level}/${n}: scored content/keys changed`);
  assert.deepEqual(master.passages, old.passages);
  assert.equal(master.examId, old.examId);
  assert.equal(org.openingJa, '日本語能力模擬試験聴解を始めます。音が聞こえるか、先に確かめましょう。');
  assert.equal(org.soundCheck.length, 2);
  assert.equal(org.generalInstructionsJa, '音の確認は終わりです。これから問題一を始めます。');
  assert.equal(org.groups[0].playExample, false);
  assert.ok(org.groups[0].instructionsJa.startsWith(`問題一は${numerals[counts[level]]}問です。メモを取っても構いません。`));
  assert.ok(!org.groups[0].instructionsJa.includes('練習'));
  assert.deepEqual(org.groups.slice(1), oldOrg.groups.slice(1), 'Later orientations/examples changed');
  assert.equal(org.openingBell.endMs - org.openingBell.startMs, 2000);
  assert.equal(audio.examplesCount, oldAudio.examplesCount - 1);
  assert.equal(audio.shortenedIntroApplied, true);
  assert.equal(audio.perceptualApproval, false);
  assert.equal(audio.continuousSha256, hash(readFileSync(resolve(root, audio.continuousAudioPath))));
  assert.equal(audio.currentMasterSha256, hash(readFileSync(resolve(root, base, 'master.ja.json'))));
  assert.equal(audio.organizationSha256, hash(readFileSync(resolve(root, base, 'listening-organization.ja.json'))));
  assert.equal(audio.items.length, oldAudio.items.length);
  const delta = audio.openingRevision.deltaMs;
  for (let j = 0; j < audio.items.length; j++) {
    const item = {...audio.items[j]}, original = oldAudio.items[j];
    assert.equal(item.startMs, original.startMs + delta);
    assert.equal(item.endMs, original.endMs + delta);
    item.startMs -= delta; item.endMs -= delta;
    assert.deepEqual(item, original, 'Scored metadata, response windows or story audio changed');
  }
  assert.equal(audio.break.musicEndMs - audio.break.musicStartMs, 60000);
  assert.equal(audio.break.sha256, oldAudio.break.sha256);
  assert.equal(audio.settings.speedScale, oldAudio.settings.speedScale);
  assert.deepEqual(audio.settings, oldAudio.settings);
  assert.ok(audio.durationMs < oldAudio.durationMs);
  assert.ok(audio.openingRevision.firstQuestionStartMs < 60000);
  assert.ok(audio.openingRevision.firstStoryAlignmentCorrelation > .95);
  const path = resolve(root, base, 'formal-trial.ts');
  const source = stripTypeScriptTypes(readFileSync(path, 'utf8')).replace(/export const /g, 'const ');
  const ctx = {require(name) { const p = resolve(dirname(path), name); return name.endsWith('.json') ? JSON.parse(readFileSync(p, 'utf8')) : {uri:p}; }, result:null};
  const prefix = `${level.toUpperCase()}_ORIGINAL_${n}`;
  vm.runInNewContext(source + `\nresult={ready:${prefix}_REGISTRATION_READY,questions:${prefix}_TRIAL,key:${prefix}_SESSION_KEY};`, ctx);
  assert.equal(ctx.result.ready, true, 'Original exam removed from ready registry');
  assert.equal(ctx.result.questions.length, master.questions.length);
  const oldAdapter = execFileSync('git', ['show', `${baseline}:${base}/formal-trial.ts`], {cwd: root, encoding: 'utf8'});
  const oldKey = oldAdapter.match(new RegExp(`${prefix}_SESSION_KEY\\s*=\\s*['\"]([^'\"]+)['\"]`))[1];
  assert.equal(ctx.result.key, oldKey);
  const first = ctx.result.questions.find(q => q.family === 'listening' && q.problemNumber === 1 && q.questionNumber === 1);
  assert.ok(first);
  assert.ok(!first.instructionJa.includes('練習'), 'Obsolete example still visible before first question');
  assert.equal(first.audio.startMs, 0);
  assert.equal(first.audio.endMs, audio.durationMs);
  total += master.questions.length;
}
console.log(`SHORT OPENING PASS: 30 ready adapters, ${total} unchanged scored responses; new intro/bell, no problem-1 practice, preserved later groups, music, pacing, IDs, keys and hashes.`);
