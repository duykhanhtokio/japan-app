// Materialize only project-authored question content; private source ledgers stay out of the app.
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..'), base = path.join(root, 'src/data/kaigo/japanese-master');
const files = fs.readdirSync(base).filter(n => /^week-\d{2}\.json$/.test(n)).sort();
assert(files.length, 'No Japanese master weeks');
const readerLines = [], questionLines = [], names = [], sectionIds = new Set(), questionIds = new Set();
fs.mkdirSync(path.join(base, 'questions'), { recursive: true });
for (const file of files) {
  const number = file.match(/\d{2}/)[0], name = 'week' + number;
  const master = JSON.parse(fs.readFileSync(path.join(base, file)));
  assert.equal(master.sourceLanguage, 'ja');
  for (const id of Object.keys(master.sections)) { assert(!sectionIds.has(id), 'Duplicate section ' + id); sectionIds.add(id); }
  const draft = JSON.parse(fs.readFileSync(path.join(root, 'docs/ssw-workspace/kaigo/japanese-master/week-' + number + '-questions.draft.json')));
  const sourceJapaneseSha256 = crypto.createHash('sha256').update(fs.readFileSync(path.join(base, file))).digest('hex');
  assert.equal(draft.sourceJapaneseSha256, sourceJapaneseSha256, 'Japanese changes require renewed question review: ' + file);
  assert(draft.questions && !Array.isArray(draft.questions), 'Questions must be keyed by stable ID: ' + file);
  const questions = {};
  for (const [id, q] of Object.entries(draft.questions)) {
    assert(id.startsWith('weekly-'), 'Invalid stable question ID ' + id);
    assert(!questionIds.has(id), 'Duplicate question ' + id); questionIds.add(id);
    assert(q.promptJa && q.optionsJa.length === 4 && q.rationalesJa.length === 4, id);
    questions[id] = { promptJa: q.promptJa, optionsJa: q.optionsJa, correctIndex: q.correctIndex, rationalesJa: q.rationalesJa };
    if (typeof q.readingJa === 'string') questions[id].readingJa = q.readingJa;
  }
  fs.writeFileSync(path.join(base, 'questions', file), JSON.stringify({ sourceLanguage: 'ja', sourceJapaneseSha256, status: 'ai_editorial_internal_preview', humanReviewed: false, domainReviewed: false, nativeReviewed: false, questions }, null, 2) + '\n');
  readerLines.push(`import ${name} from './japanese-master/${file}';`);
  questionLines.push(`import ${name} from './japanese-master/questions/${file}';`);
  names.push(name);
}
fs.writeFileSync(path.join(root, 'src/data/kaigo/japanese-master-batches.ts'), '// Generated by scripts/sync-kaigo-japanese-masters.cjs\n' + readerLines.join('\n') + '\nexport const japaneseMasterBatches = [' + names.join(', ') + '];\n');
fs.writeFileSync(path.join(root, 'src/data/kaigo/japanese-question-batches.ts'), '// Generated by scripts/sync-kaigo-japanese-masters.cjs\n' + questionLines.join('\n') + '\nexport const japaneseQuestionBatches = [' + names.join(', ') + '];\n');
console.log(JSON.stringify({ weeks: files.length, JapaneseReaderSections: sectionIds.size, JapaneseWeeklyQuestions: questionIds.size, translationsAuthored: 0 }));
