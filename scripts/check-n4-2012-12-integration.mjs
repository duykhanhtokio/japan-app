import assert from 'node:assert/strict';
import fs from 'node:fs';
const data=JSON.parse(fs.readFileSync('src/data/jlpt-official/n4-2012-12/exam.candidate.json'));
const timing=JSON.parse(fs.readFileSync('docs/jlpt-workspace/conversion/n4-2012-12/listening.alignment-candidate.json'));
