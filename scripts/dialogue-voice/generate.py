"""Resumable offline VOICEVOX NPC recording. Does not send text to external services.
python scripts/dialogue-voice/generate.py --plan /tmp/npc-plan.json --engine /path/to/run
Each finished clip is atomic. --limit bounds NEW syntheses; rerun resumes existing clips.
Generated TS registry only contains recordings which exist and decode successfully.
"""
import argparse, hashlib, io, json, pathlib, subprocess, time, urllib.parse, urllib.request, wave
root=pathlib.Path(__file__).resolve().parents[2]
def main():
 p=argparse.ArgumentParser();p.add_argument('--plan',required=True);p.add_argument('--engine',required=True);p.add_argument('--limit',type=int);p.add_argument('--port',type=int,default=50129);a=p.parse_args()
 plan=json.loads(pathlib.Path(a.plan).read_text());out=root/'assets/dialogue-voice';out.mkdir(parents=True,exist_ok=True)
 http=urllib.request.build_opener(urllib.request.ProxyHandler({}))
 def req(route,data=None):
  return http.open(urllib.request.Request(f'http://127.0.0.1:{a.port}'+route,data=data,headers={'Content-Type':'application/json'}),timeout=180).read()
 engine=pathlib.Path(a.engine).resolve();log=open('/tmp/dialogue-voicevox.log','ab')
 proc=subprocess.Popen([str(engine),'--host','127.0.0.1','--port',str(a.port),'--cpu_num_threads','2'],cwd=engine.parent,stdout=log,stderr=log)
 try:
  for _ in range(120):
   if proc.poll() is not None:raise RuntimeError('Engine exited; see /tmp/dialogue-voicevox.log')
   try:req('/version');break
   except OSError:time.sleep(.5)
  else:raise RuntimeError('Engine startup timeout')
  assert json.loads(req('/version'))==plan['engine']['version'], 'Engine version differs from approved configuration'
  available={s['id'] for v in json.loads(req('/speakers')) for s in v['styles']}
  assert {8,118,11,21}<=available,'Approved four voices not all available'
  entries={};assets={};made=0
  for row in plan['rows']:
   # Include text, pronunciation, engine version, voice and settings in the cache identity.
   identity={k:row[k] for k in ['sourceJa','spokenKana','speakerId']};identity.update(engine=plan['engine'],settings=plan['settings'])
   key=hashlib.sha256(json.dumps(identity,ensure_ascii=False,sort_keys=True).encode()).hexdigest();mp3=out/(key+'.mp3');meta=out/(key+'.json')
   if not mp3.exists() or not meta.exists():
    if a.limit is not None and made>=a.limit:continue
    query=json.loads(req('/audio_query?'+urllib.parse.urlencode({'speaker':row['speakerId'],'text':row['sourceJa']}),b''))
    query.update(plan['settings'])
    # Preserve Japanese contextual prosody; kana is retained in provenance for pronunciation QA,
    # not blindly substituted into VOICEVOX (which would lose lexical accent information).
    wav=req('/synthesis?speaker='+str(row['speakerId']),json.dumps(query).encode())
    with wave.open(io.BytesIO(wav),'rb') as w:
     assert w.getnchannels()==1 and w.getframerate()==24000 and w.getnframes()>0
     durationMs=round(w.getnframes()*1000/w.getframerate())
    temp=out/(key+'.tmp.mp3')
    subprocess.run(['ffmpeg','-v','error','-y','-f','wav','-i','pipe:0','-codec:a','libmp3lame','-b:a','48k',str(temp)],input=wav,check=True)
    subprocess.run(['ffmpeg','-v','error','-i',str(temp),'-f','null','-'],check=True)
    temp.replace(mp3)
    meta.write_text(json.dumps({**identity,'durationMs':durationMs,'sha256':hashlib.sha256(mp3.read_bytes()).hexdigest(),'nativeReviewed':False},ensure_ascii=False)+'\n');made+=1
    print(json.dumps({'newClips':made,'turnId':row['turnId'],'role':row['role'],'durationMs':durationMs}),flush=True)
   metadata=json.loads(meta.read_text());assert metadata['sha256']==hashlib.sha256(mp3.read_bytes()).hexdigest()
   assets[key]=f"require('../../../assets/dialogue-voice/{key}.mp3')"
   entries.setdefault(row['scenarioId'],{})[row['turnId']]={'sourceJa':row['sourceJa'],'role':row['role'],'speakerId':row['speakerId'],'clip':key,'durationMs':metadata['durationMs']}
  target=root/'src/data/dialogue-content/npc-audio.generated.ts'
  content="// Generated by scripts/dialogue-voice/generate.py; exact-source-bound NPC recordings.\nexport const npcAudioClips: Record<string, number> = {\n"+''.join(json.dumps(k)+': '+v+',\n' for k,v in assets.items())+"};\nexport const npcAudioEntries: Record<string, Record<string, {sourceJa:string;role:string;speakerId:number;clip:string;durationMs:number}>> = "+json.dumps(entries,ensure_ascii=False)+";\n"
  temp=target.with_suffix('.tmp');temp.write_text(content);temp.replace(target)
  print(json.dumps({'newClips':made,'availableClips':len(assets),'recordedTurns':sum(map(len,entries.values())),'plannedTurns':len(plan['rows']),'unverifiedCategories':plan['unverifiedCategories'],'complete':sum(map(len,entries.values()))==len(plan['rows']) and not plan['unverifiedCategories']}),flush=True)
 finally:
  proc.terminate()
  try:proc.wait(timeout=15)
  except subprocess.TimeoutExpired:proc.kill();proc.wait()
  log.close()
if __name__=='__main__':main()
