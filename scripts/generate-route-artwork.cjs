/* global __dirname */
// Derive static image preparation from the real route/component import graph.
// Dynamic city/location/maps and selected exam images are prepared separately.
const fs = require('node:fs');
const path = require('node:path');
const parser = require('@babel/parser');
const root = path.resolve(__dirname, '..');
const excluded = /(?:\/services\/|\/data\/(?:jlpt-official|jlpt-mock|generated|world-map-config)|farm-cosmetic-assets|city-images\.generated|location-backgrounds\.generated|\/ui\/(?:prepareSceneRoute|route-artwork|common-artwork|AppBackdrop|HomeTokuteiBackdrop))/;
function resolve(from, request) {
  let base = request.startsWith('@/') ? path.join(root, 'src', request.slice(2))
    : request.startsWith('.') ? path.resolve(path.dirname(from), request) : null;
  if (!base) return null;
  if (request.startsWith('@/') && !fs.existsSync(base) && fs.existsSync(path.join(root, request.slice(2)))) base = path.join(root, request.slice(2));
  return [base, base + '.tsx', base + '.ts', base + '.json', path.join(base, 'index.tsx'), path.join(base, 'index.ts')]
    .find(file => fs.existsSync(file) && fs.statSync(file).isFile());
}
function artwork(file, visited = new Set()) {
  if (visited.has(file) || excluded.test(file) || !/\.tsx?$/.test(file)) return new Set();
  visited.add(file);
  const ast = parser.parse(fs.readFileSync(file, 'utf8'), { sourceType: 'module', plugins: ['typescript', 'jsx'] });
  const images = new Set();
  function visit(node) {
    if (!node || typeof node !== 'object') return;
    if (node.type === 'CallExpression' && node.callee.name === 'require' && node.arguments[0]?.type === 'StringLiteral') {
      const request = node.arguments[0].value;
      if (/\.(?:png|jpe?g|webp|gif)$/i.test(request)) {
        const image = resolve(file, request);
        if (!image) throw new Error(`Missing static artwork: ${file} -> ${request}`);
        images.add(image);
      }
    }
    if ((node.type === 'ImportDeclaration' || node.type === 'ExportNamedDeclaration' || node.type === 'ExportAllDeclaration') && node.source && node.importKind !== 'type') {
      const target = resolve(file, node.source.value);
      if (target) for (const image of artwork(target, visited)) images.add(image);
    }
    for (const [key, value] of Object.entries(node)) {
      if (['loc', 'start', 'end'].includes(key)) continue;
      if (Array.isArray(value)) value.forEach(visit); else if (value && typeof value === 'object') visit(value);
    }
  }
  visit(ast);
  return images;
}
const directory = path.join(root, 'src/app');
const routes = fs.readdirSync(directory, { recursive: true }).filter(file => file.endsWith('.tsx') && !file.endsWith('_layout.tsx')).sort();
const assets = [];
const entries = routes.map(file => {
  const route = '/' + file.replace(/\.tsx$/, '').replace(/(?:^|\/)index$/, '');
  const images = [...artwork(path.join(directory, file))].sort();
  const indexes = images.map(image => { let index = assets.indexOf(image); if (index < 0) { index = assets.length; assets.push(image); } return index; });
  return `  ${JSON.stringify(route)}: [${indexes.join(',')}].map(index => ARTWORK[index]),`;
});
const target = path.join(root, 'src/components/ui/route-artwork.ts');
const output = '// Generated by scripts/generate-route-artwork.cjs; do not hand-edit.\n'
  + '// Dynamic route-specific scenes and selected exam illustrations are added at runtime.\n'
  + 'const ARTWORK = [\n' + assets.map(image => `  require(${JSON.stringify('../../' + path.relative(path.join(root, 'src'), image).replaceAll('\\', '/'))}),`).join('\n') + '\n];\n'
  + 'export const ROUTE_ARTWORK: Record<string, number[]> = {\n' + entries.join('\n') + '\n};\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Route artwork inventory is stale; regenerate it.');
} else fs.writeFileSync(target, output);
console.log(`ROUTE ARTWORK ${process.argv.includes('--check') ? 'PASS' : 'GENERATED'}: ${routes.length} route templates, ${assets.length} distinct static images.`);
