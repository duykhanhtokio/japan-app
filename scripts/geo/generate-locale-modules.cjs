#!/usr/bin/env node
'use strict';
// Generates 12 independent locale module graphs from actual batch filenames.
// Offline, deterministic; no content edits and no production runtime switch.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../..');
const base=path.join(root,'src/data/dialogue-content/locale-batches');
const out=path.join(root,'src/data/generated/geo-locales');
const locales=fs.readdirSync(base,{withFileTypes:true}).filter(x=>x.isDirectory()).map(x=>x.name).sort();
const generated=[];
const index=['// Generated by scripts/geo/generate-locale-modules.cjs','export type RawLocaleModule={loadBatch:(id:string)=>unknown|undefined};','export const localeModules:Record<string,()=>Promise<RawLocaleModule>>={'];
let files=0;
for(const locale of locales){
 const batches=fs.readdirSync(path.join(base,locale)).filter(f=>f.endsWith('.json')).sort();
 files+=batches.length;
 const body=['// Generated offline locale module','const batches:Record<string,()=>unknown>={',...batches.map(f=>'  '+JSON.stringify(f.slice(0,-5))+':()=>require('+JSON.stringify('../../dialogue-content/locale-batches/'+locale+'/'+f)+'),'),'};','export function loadBatch(id:string):unknown|undefined{return batches[id]?.();}',''];
 generated.push([path.join(out,locale+'.ts'),body.join('\n')]);
 index.push('  '+JSON.stringify(locale)+':()=>import('+JSON.stringify('./'+locale)+'),');
}
index.push('};','');
generated.push([path.join(out,'index.ts'),index.join('\n')]);
const mode=process.argv[2];
if(!['--check','--write'].includes(mode)||process.argv.length!==3)throw Error('Usage: node scripts/geo/generate-locale-modules.cjs --check|--write');
if(mode==='--write'){fs.mkdirSync(out,{recursive:true});for(const [p,c] of generated)fs.writeFileSync(p,c);}
console.log(JSON.stringify({mode,languages:locales.length,batchFiles:files,modules:generated.length,output:out},null,2));
