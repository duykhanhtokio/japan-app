#!/usr/bin/env node
'use strict';
// Generate an Ibaraki-only Metro module with literal require() calls.
// This pilot is deliberately not wired into the production dialogue loader.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../..');
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const cities=read('src/data/generated/cities.json');
const lc=read('src/data/generated/life-on-demand/location-cities.json');
const sl=read('src/data/generated/life-on-demand/scenario-locations.json');
const eligible=new Set(cities.filter(c=>c.prefectureId==='PRF-008').map(c=>c.id));
const ids=Object.entries(sl).filter(([id,loc])=>eligible.has(lc[loc])).map(([id])=>id).sort();
if(ids.length!==277)throw Error('Expected 277 Ibaraki scenarios; got '+ids.length);
for(const id of ids)if(!fs.existsSync(path.join(root,'src/data/generated/dialogues',id+'.json')))throw Error('Missing '+id);
const output=path.join(root,'src/data/generated/geo-pilot/ibaraki-dialogues.ts');
const lines=[
'// Generated by scripts/geo/generate-ibaraki-module.cjs. Do not edit manually.',
'// Pilot-only static require graph. Not imported by production runtime.',
'type DialogueModule = unknown;',
'const modules: Record<string, () => DialogueModule> = {',
...ids.map(id=>'  '+JSON.stringify(id)+': () => require('+JSON.stringify('../dialogues/'+id+'.json')+'),'),
'};',
'export const ibarakiScenarioIds = '+JSON.stringify(ids)+' as const;',
'export function loadIbarakiRawDialogue(scenarioId: string): unknown | undefined {',
'  return modules[scenarioId]?.();',
'}',
''
];
const args=process.argv.slice(2);
if(args.length!==1||!['--check','--write'].includes(args[0]))throw Error('Usage: node scripts/geo/generate-ibaraki-module.cjs --check|--write');
const source=lines.join('\n');
if(args[0]==='--write'){fs.mkdirSync(path.dirname(output),{recursive:true});fs.writeFileSync(output,source);}
console.log(JSON.stringify({mode:args[0],prefectureId:'PRF-008',scenarios:ids.length,output,generatedBytes:Buffer.byteLength(source),runtimeWired:false},null,2));
