'use strict';
// Index existing authored bytes only. No content or translations are rewritten.
const fs = require('node:fs');
const path = require('node:path');
function generate(root) {
    const dir = path.join(root, 'src/data/generated/vocabulary-practical-example-shards');
    const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
    const byId = {};
    const loaders = manifest.files.map(({file}, index) => {
        if (!/^direct-\d+\.json$/.test(file)) throw Error('Invalid shard filename');
        const entries = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8')).entries;
        for (const id of Object.keys(entries)) byId[id] = index; // Last shard wins, as before.
        return `    () => require('./vocabulary-practical-example-shards/${file}').entries,`;
    });
    fs.writeFileSync(path.join(dir, 'index.json'), JSON.stringify(byId) + '\n');
    const source = `// Generated by scripts/generate-vocabulary-shard-loader.cjs. All content remains offline.
import { lazyRecord } from '@/services/lazy-record';
import type { AppLanguageCode } from '@/i18n/languages';
type PracticalExample = {
    word: string; reading: string; sourceJa: string;
    translations: Record<Exclude<AppLanguageCode, 'ja'>, string>;
};
const loaders: (() => Record<string, PracticalExample>)[] = [
${loaders.join('\n')}
];
const shardById = lazyRecord(() => require('./vocabulary-practical-example-shards/index.json') as Record<string, number>);
export function getPracticalExampleShardEntry(id: string): PracticalExample | undefined {
    return Object.prototype.hasOwnProperty.call(shardById, id) ? loaders[shardById[id]]()[id] : undefined;
}
// Compatibility for callers that intentionally enumerate the complete collection.
export const practicalExampleShardEntries = lazyRecord(() => Object.assign({}, ...loaders.map(load => load())) as Record<string, PracticalExample>);
`;
    fs.writeFileSync(path.join(root, 'src/data/generated/vocabulary-practical-example-shards.ts'), source);
    return {shards:loaders.length, ids:Object.keys(byId).length};
}
module.exports = generate;
if (require.main === module) console.log(JSON.stringify(generate(path.resolve(__dirname,'..'))));
