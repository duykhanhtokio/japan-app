def add(lesson_id, ps, operation, condition, distinct, comparisons, stem, options, reasons, hold=''):
    lesson = lessons[lesson_id]
    assert lesson_id in allocation['lessonIds'] and '2' in lesson['levels']
    paragraphs = [next(p for p in lesson['paragraphs'] if p['id'] == lesson_id+'-p'+str(n)) for n in ps]
    kids = list(dict.fromkeys(k for p in paragraphs for k in p['knowledgeIds']))
    i = len(questions)+1
    oid = f'AGR-ASSESS-P28-W5-{i:02}'
    for qid in comparisons:
        assert qid in existing, qid
    objectives.append({
        'id': oid, 'lessonId': lesson_id, 'paragraphIds': [p['id'] for p in paragraphs],
        'knowledgeIds': kids, 'operationJa': operation, 'conditionJa': condition,
        'whyDistinctFromExistingJa': distinct, 'comparedQuestionIds': comparisons,
        'sourceHoldAssessmentJa': hold or '現在の本文の範囲に限定する。写真認識、実機性能、製品条件、地域共通の処方の認定は行わない。',
    })
    assert len(options) == len(reasons) == len(set(options)) == 4
    correct = positions[i-1]
    wrongs = list(zip(options[1:], reasons[1:]))
    if i % 2:
        wrongs.reverse()
    pairs = wrongs[:correct]+[(options[0], reasons[0])]+wrongs[correct:]
    questions.append({
        'id': f'agr-2-m02-q{i:02}', 'objectiveId': oid, 'topicJa': lesson['chapter'],
        'stemJa': stem, 'optionsJa': [a for a, _ in pairs], 'correctIndex': correct,
        'optionReasonsJa': [r for _, r in pairs], 'lessonId': lesson_id,
        'lessonSourceHash': lesson['sourceHash'], 'knowledgeIds': kids,
        'nativeReviewed': False, 'domainReviewed': False,
    })


